def normalize_text(text: str) -> str:
  
    normalized = " ".join(
        text.strip().split()
    )

    if not normalized:
        return ""

    for wrong in sorted(
        STT_CORRECTIONS.keys(),
        key=len,
        reverse=True,
    ):
        correct = STT_CORRECTIONS[wrong]

        normalized = normalized.replace(
            wrong,
            correct,
        )

  
    if "후앙" in normalized:
        normalized = normalized.replace(
            "관계하세요",
            "환기하세요",
        )
        normalized = normalized.replace(
            "관계해 주세요",
            "환기해 주세요",
        )

     
        normalized = normalized.replace(
            "환경하세요",
            "환기하세요",
        )
        normalized = normalized.replace(
            "환경해 주세요",
            "환기해 주세요",
        )
        normalized = normalized.replace(
            "계속 환경",
            "계속 환기",
        )

        normalized = normalized.replace(
            "끌지 말고",
            "끄지 말고",
        )


    normalized = re.sub(
        r"\s+",
        " ",
        normalized,
    ).strip()

    return normalized


