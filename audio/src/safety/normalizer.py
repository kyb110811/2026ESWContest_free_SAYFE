def normalize_text(text: str) -> str:
    """
    Whisper STT 결과에서 반복적으로 발생하는
    건설안전 관련 오인식을 교정한다.

    현장 은어를 표준어로 변환하는 작업은
    construction_rules.py에서 별도로 수행한다.
    """

    normalized = " ".join(
        text.strip().split()
    )

    if not normalized:
        return ""

    # 긴 표현부터 교정하여 부분 치환 충돌 방지
    for wrong in sorted(
        STT_CORRECTIONS.keys(),
        key=len,
        reverse=True,
    ):
        correct = STT_CORRECTIONS[wrong]

        normalized = normalized.replace(
            wrong,
            correct,
        )

    # 후앙 문맥에서만 반복 STT 오인식을 제한적으로 복구
    # 일반 문장의 "관계", "호황", "포항"을 잘못 바꾸지 않도록
    # 후앙이 이미 복원된 경우에만 적용한다.
    if "후앙" in normalized:
        normalized = normalized.replace(
            "관계하세요",
            "환기하세요",
        )
        normalized = normalized.replace(
            "관계해 주세요",
            "환기해 주세요",
        )

        # 후앙/환풍기 문맥에서 Whisper가
        # "환기"를 "환경"으로 인식하는 반복 오류 복구
        normalized = normalized.replace(
            "환경하세요",
            "환기하세요",
        )
        normalized = normalized.replace(
            "환경해 주세요",
            "환기해 주세요",
        )
        normalized = normalized.replace(
            "계속 환경",
            "계속 환기",
        )

        normalized = normalized.replace(
            "끌지 말고",
            "끄지 말고",
        )

    # 공백 정리
    normalized = re.sub(
        r"\s+",
        " ",
        normalized,
    ).strip()

    return normalized


