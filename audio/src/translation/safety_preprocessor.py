# =========================================================
# 기본 텍스트 정리
# =========================================================

def _clean_text(text: str) -> str:
    text = " ".join(
        text.strip().split()
    )

    text = re.sub(
        r"\s+([,.!?])",
        r"\1",
        text,
    )

    return text.strip()


# =========================================================
# 안전 번역용 문장 분리
# =========================================================

def split_safety_units(
    text: str,
) -> list[str]:
    """
    복합 안전문장을 짧은 의미 단위로 분리한다.

    예:
        유해가스가 감지되었습니다.
        장비를 즉시 멈추십시오.

    각각 독립적으로 NLLB에 전달할 수 있도록 한다.
    """

    text = _clean_text(text)

    if not text:
        return []

    # 마침표/물음표/느낌표 기준 분리
    parts = re.split(
        r"(?<=[.!?])\s+",
        text,
    )

    units: list[str] = []

    for part in parts:
        part = part.strip()

        if not part:
            continue

        # 문장부호를 유지한다.
        # 질문/명령/감탄의 의미가 NLLB 번역에서 보존되도록 한다.
        if part:
            units.append(part)

    return units


# =========================================================
# 메인 전처리
# =========================================================

def preprocess_for_translation(
    text: str,
) -> dict[str, Any]:
    """
    정규화된 건설안전 한국어를 NLLB 친화적인
    명시적 안전 한국어로 변환한다.

    Returns
    -------
    original:
        입력 한국어

    processed:
        전체 전처리 결과

    units:
        NLLB에 독립적으로 넣을 안전 의미 단위

    matches:
        어떤 규칙이 적용됐는지 기록
    """

    original = _clean_text(text)

    if not original:
        return {
            "original": "",
            "processed": "",
            "units": [],
            "matches": [],
        }

    # -----------------------------------------------------
    # 0. 현장 은어 / 건설용어 표준화
    # -----------------------------------------------------
    construction_result = normalize_construction_korean(original)

    processed = _clean_text(
        str(construction_result.get("normalized", original))
    )

    matches: list[dict[str, str]] = []

    for item in construction_result.get("matches", []) or []:
        matches.append({
            "type": "construction_rule",
            "original": str(item.get("original", "")),
            "replacement": str(item.get("replacement", "")),
        })

    # -----------------------------------------------------
    # 1. 안전 행동 표현 먼저 적용
    # -----------------------------------------------------

    for source in sorted(
        PHRASE_REWRITES.keys(),
        key=len,
        reverse=True,
    ):
        if source in processed:
            target = PHRASE_REWRITES[source]

            processed = processed.replace(
                source,
                target,
            )

            matches.append({
                "type": "phrase",
                "original": source,
                "replacement": target,
            })

    # -----------------------------------------------------
    # 1-2. 현장 작업 의미 명확화
    # -----------------------------------------------------

    for source in sorted(
        WORK_PHRASE_REWRITES.keys(),
        key=len,
        reverse=True,
    ):
        if source in processed:
            target = WORK_PHRASE_REWRITES[source]

            processed = processed.replace(
                source,
                target,
            )

            matches.append({
                "type": "work_phrase",
                "original": source,
                "replacement": target,
            })


    # -----------------------------------------------------
    # 2. 건설 전문용어 의미 확장
    # -----------------------------------------------------

    for source in sorted(
        TERM_REWRITES.keys(),
        key=len,
        reverse=True,
    ):
        if source in processed:
            target = TERM_REWRITES[source]

            processed = processed.replace(
                source,
                target,
            )

            matches.append({
                "type": "term",
                "original": source,
                "replacement": target,
            })

    processed = _clean_text(
        processed
    )

    # -----------------------------------------------------
    # 3. 전문용어 표준화 후 행동 표현 2차 적용
    # -----------------------------------------------------
    #
    # 예:
    #   환풍기 -> 환기 장치
    #   바닥 고르기 -> 바닥 평탄화
    #
    # TERM_REWRITES 이후에 만들어진 표현을
    # 보다 명시적인 안전 행동 문장으로 다시 변환한다.
    # -----------------------------------------------------

    for source in sorted(
        PHRASE_REWRITES.keys(),
        key=len,
        reverse=True,
    ):
        if source in processed:
            target = PHRASE_REWRITES[source]

            if source != target:
                processed = processed.replace(
                    source,
                    target,
                )

                matches.append({
                    "type": "phrase_second_pass",
                    "original": source,
                    "replacement": target,
                })

    # -----------------------------------------------------
    # 3-2. TERM / PHRASE 변환 후 현장 작업 표현 2차 적용
    # -----------------------------------------------------
    #
    # 작업준비 -> 작업 준비
    # 바닥 고르기 -> 바닥 평탄화 -> 명시적 작업 표현
    # 등의 변환 이후 새롭게 만들어진 패턴을 다시 검사한다.
    # -----------------------------------------------------

    for source in sorted(
        WORK_PHRASE_REWRITES.keys(),
        key=len,
        reverse=True,
    ):
        if source in processed:
            target = WORK_PHRASE_REWRITES[source]

            if source != target:
                processed = processed.replace(
                    source,
                    target,
                )

                matches.append({
                    "type": "work_phrase_second_pass",
                    "original": source,
                    "replacement": target,
                })

    processed = _clean_text(
        processed
    )

    # -----------------------------------------------------
    # 4. 독립 안전 의미 단위 분리
    # -----------------------------------------------------

    units = split_safety_units(
        processed
    )

    return {
        "original": original,
        "processed": processed,
        "units": units,
        "matches": matches,
    }


